'use strict';

const fetch = require('node-fetch');

const EPA_BASE   = 'https://data.epa.gov/efservice';
const TIMEOUT_MS = 12000;

async function epaFetch(path) {
  const url = `${EPA_BASE}${path}`;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      signal: controller.signal,
      headers: { 'Accept': 'application/json', 'User-Agent': 'WellWater/1.0' }
    });
    clearTimeout(timer);
    if (!res.ok) return [];
    const text = await res.text();
    if (!text || text.trim() === '[]') return [];
    try { return JSON.parse(text); } catch { return []; }
  } catch { clearTimeout(timer); return []; }
}

const FIVE_YEARS_AGO = Date.now() - 5 * 365.25 * 24 * 60 * 60 * 1000;

module.exports = async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  if (req.method === 'OPTIONS') return res.status(200).end();

  const pwsid = (req.query.pwsid || '').toUpperCase().trim();
  if (!pwsid) return res.status(400).json({ error: 'INVALID_PWSID' });

  const sysRows = await epaFetch(`/WATER_SYSTEM/PWSID/${pwsid}/JSON`);
  if (!Array.isArray(sysRows) || sysRows.length === 0) {
    return res.status(404).json({ error: 'NO_SYSTEM' });
  }
  const sys = sysRows[0];
  const name     = sys.pws_name   || 'your local water system';
  const city     = sys.city_name  || '';
  const state    = sys.state_code || '';
  const location = [city, state].filter(Boolean).join(', ');

  const rawViols = await epaFetch(`/VIOLATION/PWSID/${pwsid}/JSON`);
  const viols = (Array.isArray(rawViols) ? rawViols : []).filter(v => {
    const d = v.compliance_period_begin_date || v.occurrence_submit_date;
    return d && new Date(d).getTime() >= FIVE_YEARS_AGO;
  });

  const catCode  = v => (v.violation_category_code || '').toUpperCase();
  const typeCode = v => (v.violation_type_code      || '').toUpperCase();
  const isHealth = v => ['MCL','MRDL','TT'].some(c => catCode(v) === c || typeCode(v).startsWith(c));
  const isOpen   = v => (v.compliance_status_code || '').toUpperCase() !== 'R' && !v.return_to_compliance_period_end_date;

  const healthOpen  = viols.filter(v => isHealth(v) && isOpen(v)).length;
  const healthTotal = viols.filter(v => isHealth(v)).length;

  if (healthOpen === 0 && healthTotal === 0) return res.status(204).end();

  const letter = [
    'Dear Representative,',
    '',
    `I am writing as a constituent concerned about the drinking water safety record of ${name}` +
    ` (EPA PWSID: ${pwsid})${location ? `, which serves my community in ${location}` : ''}.`,
    '',
    `According to the EPA\'s Safe Drinking Water Information System (SDWIS), this water system has recorded:`,
    `  • ${healthOpen} currently open health-based Safe Drinking Water Act violation${healthOpen !== 1 ? 's' : ''}`,
    `  • ${healthTotal} total health-based violation${healthTotal !== 1 ? 's' : ''} in the past 5 years`,
    '',
    'Health-based violations mean contaminants may have exceeded federal safety limits set to protect public health under the Safe Drinking Water Act.',
    '',
    'I respectfully ask that you:',
    '',
    `1. Request a briefing from the EPA and state primacy agency on the compliance status of ${name}`,
    '2. Inquire whether affected residents received timely public notice as required by law',
    '3. Ensure federal infrastructure funding is reaching water systems with chronic compliance issues',
    '',
    'Water safety is a fundamental public health issue. Thank you for your attention.',
    '',
    'Sincerely,',
    '[Your name]',
    '[Your address]',
    '',
    '---',
    'Data source: EPA Envirofacts SDWIS · https://data.epa.gov/efservice/',
    'Generated by WellWater · A nonpartisan public health tool',
  ].join('\n');

  return res.setHeader('Content-Type', 'text/plain').status(200).send(letter);
};
